%% 构建多刚体车辆系统 M、C、K 矩阵

function [Mlc,Klc,Clc] = Matrix_Vehicle_RW(Par_Vehicle)

Mw = Par_Vehicle.Mw;
Jwx = Par_Vehicle.Jwx;
Jwy = Par_Vehicle.Jwy;
Jwz = Par_Vehicle.Jwz;
Mb = Par_Vehicle.Mb;
Jbx = Par_Vehicle.Jbx;
Jby = Par_Vehicle.Jby;
Jbz = Par_Vehicle.Jbz;
Mc = Par_Vehicle.Mc;
Jcx = Par_Vehicle.Jcx;
Jcy = Par_Vehicle.Jcy;
Jcz = Par_Vehicle.Jcz;
K1z = Par_Vehicle.K1z; C1z = Par_Vehicle.C1z;
K1y = Par_Vehicle.K1y; C1y = Par_Vehicle.C1y;
K1x = Par_Vehicle.K1x; C1x = Par_Vehicle.C1x;
K2z = Par_Vehicle.K2z; C2z = Par_Vehicle.C2z;
K2y = Par_Vehicle.K2y; C2y = Par_Vehicle.C2y;
K2x = Par_Vehicle.K2x; C2x = Par_Vehicle.C2x;
Lb1 = Par_Vehicle.Lb1; Lb2 = Par_Vehicle.Lb2;
Ll1 = Par_Vehicle.Ll1; Ll2 = Par_Vehicle.Ll2;
H2 = Par_Vehicle.H2; H3 = Par_Vehicle.H3; H4 = Par_Vehicle.H4;
Kr = Par_Vehicle.Kr; K2b = Par_Vehicle.K2b;

%%% ===================== 车辆质量、刚度、阻尼矩阵
% 列车质量（位移变分为行，加速度为列）
Mlc=zeros(35,35);
i1=0;
while i1<4
    Mlc((5*i1+1),(5*i1+1))=Mw;
    Mlc((5*i1+2),(5*i1+2))=Mw;
    Mlc((5*i1+3),(5*i1+3))=Jwx;         %轮对侧滚惯量 Jwf  kg.m^2
    Mlc((5*i1+4),(5*i1+4))=Jwy;         %轮对点头惯量 Jwf  kg.m^2        
    Mlc((5*i1+5),(5*i1+5))=Jwz;         %轮对摇头惯量 Jwc  kg.m^2
    i1=i1+1;
end

i1=0;
while i1<2
    Mlc((20+5*i1+1),(20+5*i1+1))=Mb;
    Mlc((20+5*i1+2),(20+5*i1+2))=Mb;
    Mlc((20+5*i1+3),(20+5*i1+3))=Jbx;
    Mlc((20+5*i1+4),(20+5*i1+4))=Jby;
    Mlc((20+5*i1+5),(20+5*i1+5))=Jbz;
    i1=i1+1;
end
Mlc((30+1),(30+1))=Mc;
Mlc((30+2),(30+2))=Mc;
Mlc((30+3),(30+3))=Jcx;
Mlc((30+4),(30+4))=Jcy;
Mlc((30+5),(30+5))=Jcz;

%列车刚度（位移变分为行，位移为列）
Klc=zeros(35,35);
%%% 一系悬挂 K1z、K1y、K1x
i1=0;   % i1 = 0:1:7;
while i1<8
    i1g1=fix((i1+1+3)/4);       %%% 转向架序号 i=1,2
    i1g2=fix((i1+1+1)/2);       %%% 轮对序号 m=1,2,3,4
    i1g3=fix((3*(i1+1)+1)/2);   %%% 车轮位置序号 ...............j+m=2,3,5,6,8,9,11,12 Left/Right
    i1g4=fix((i1+1-1)/2);       %%% m±1=[0,0,1,1,2,2,3,3;]
    
    %%% 21、26列：zti(i=1,2)
    Klc((20+5*(i1g1-1)+1),(20+5*(i1g1-1)+1)) = Klc((20+5*(i1g1-1)+1),(20+5*(i1g1-1)+1))+K1z;
    Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+1)) = Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+1))+((-1)^(i1+1))*Lb1*K1z;
    Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+1)) = Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+1))+((-1)^i1g2)*Ll1*K1z;
    Klc((5*(i1g2-1)+1),(20+5*(i1g1-1)+1)) = Klc((5*(i1g2-1)+1),(20+5*(i1g1-1)+1))-K1z;
    Klc((5*(i1g2-1)+3),(20+5*(i1g1-1)+1)) = Klc((5*(i1g2-1)+3),(20+5*(i1g1-1)+1))-((-1)^(i1+1))*Lb1*K1z;
    %%% 1、6、11、16列：zwm(m = 1,2,3,4)
    Klc((20+5*(i1g1-1)+1),(5*(i1g2-1)+1)) = Klc((20+5*(i1g1-1)+1),(5*(i1g2-1)+1))-K1z;
    Klc((20+5*(i1g1-1)+3),(5*(i1g2-1)+1)) = Klc((20+5*(i1g1-1)+3),(5*(i1g2-1)+1))-((-1)^(i1+1))*Lb1*K1z;
    Klc((20+5*(i1g1-1)+4),(5*(i1g2-1)+1)) = Klc((20+5*(i1g1-1)+4),(5*(i1g2-1)+1))-((-1)^i1g2)*Ll1*K1z;
    Klc((5*(i1g2-1)+1),(5*(i1g2-1)+1)) = Klc((5*(i1g2-1)+1),(5*(i1g2-1)+1))+K1z;
    Klc((5*(i1g2-1)+3),(5*(i1g2-1)+1)) = Klc((5*(i1g2-1)+3),(5*(i1g2-1)+1))+((-1)^(i1+1))*Lb1*K1z;
    %%% 23、28列：φti(i = 1,2)   
    Klc((20+5*(i1g1-1)+1),(20+5*(i1g1-1)+3)) = Klc((20+5*(i1g1-1)+1),(20+5*(i1g1-1)+3))+((-1)^(i1+1))*Lb1*K1z;
    Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+3)) = Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+3))+Lb1*Lb1*K1z;
    Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+3)) = Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+3))+((-1)^i1g3)*Lb1*Ll1*K1z;
    Klc((5*(i1g2-1)+1),(20+5*(i1g1-1)+3)) = Klc((5*(i1g2-1)+1),(20+5*(i1g1-1)+3))-((-1)^(i1+1))*Lb1*K1z;
    Klc((5*(i1g2-1)+3),(20+5*(i1g1-1)+3)) = Klc((5*(i1g2-1)+3),(20+5*(i1g1-1)+3))-Lb1*Lb1*K1z;
    %%% 24、29列：βti(i = 1,2)      
    Klc((20+5*(i1g1-1)+1),(20+5*(i1g1-1)+4)) = Klc((20+5*(i1g1-1)+1),(20+5*(i1g1-1)+4))+((-1)^i1g2)*Ll1*K1z;
    Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+4)) = Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+4))+((-1)^i1g3)*Lb1*Ll1*K1z;
    Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+4)) = Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+4))+Ll1*Ll1*K1z;
    Klc((5*(i1g2-1)+1),(20+5*(i1g1-1)+4)) = Klc((5*(i1g2-1)+1),(20+5*(i1g1-1)+4))-((-1)^i1g2)*Ll1*K1z;
    Klc((5*(i1g2-1)+3),(20+5*(i1g1-1)+4)) = Klc((5*(i1g2-1)+3),(20+5*(i1g1-1)+4))-((-1)^i1g3)*Lb1*Ll1*K1z;
    %%% 3、8、13、18列：φwm(m=1,2,3,4)    
    Klc((20+5*(i1g1-1)+1),(5*(i1g2-1)+3))=Klc((20+5*(i1g1-1)+1),(5*(i1g2-1)+3))-((-1)^(i1+1))*Lb1*K1z;
    Klc((20+5*(i1g1-1)+3),(5*(i1g2-1)+3))=Klc((20+5*(i1g1-1)+3),(5*(i1g2-1)+3))-Lb1*Lb1*K1z;
    Klc((20+5*(i1g1-1)+4),(5*(i1g2-1)+3))=Klc((20+5*(i1g1-1)+4),(5*(i1g2-1)+3))-((-1)^i1g3)*Lb1*Ll1*K1z;
    Klc((5*(i1g2-1)+1),(5*(i1g2-1)+3))=Klc((5*(i1g2-1)+1),(5*(i1g2-1)+3))+((-1)^(i1+1))*Lb1*K1z;
    Klc((5*(i1g2-1)+3),(5*(i1g2-1)+3))=Klc((5*(i1g2-1)+3),(5*(i1g2-1)+3))+Lb1*Lb1*K1z;    
    
    %%% 22、27行：δyti(i = 1,2)
    Klc((20+5*(i1g1-1)+2),(20+5*(i1g1-1)+2)) = Klc((20+5*(i1g1-1)+2),(20+5*(i1g1-1)+2))+K1y;
    Klc((20+5*(i1g1-1)+2),(20+5*(i1g1-1)+3)) = Klc((20+5*(i1g1-1)+2),(20+5*(i1g1-1)+3))-H4*K1y;
    Klc((20+5*(i1g1-1)+2),(20+5*(i1g1-1)+5)) = Klc((20+5*(i1g1-1)+2),(20+5*(i1g1-1)+5))+((-1)^i1g4)*Ll1*K1y;
    Klc((20+5*(i1g1-1)+2),(5*(i1g2-1)+2)) = Klc((20+5*(i1g1-1)+2),(5*(i1g2-1)+2))-K1y;
    %%% 23、28行：δφti(i = 1,2)    
    Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+2)) = Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+2))-H4*K1y;
    Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+3)) = Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+3))+H4*H4*K1y;
    Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+5)) = Klc((20+5*(i1g1-1)+3),(20+5*(i1g1-1)+5))-((-1)^i1g4)*Ll1*H4*K1y;
    Klc((20+5*(i1g1-1)+3),(5*(i1g2-1)+2)) = Klc((20+5*(i1g1-1)+3),(5*(i1g2-1)+2))+H4*K1y;
    %%% 25、30行：δψti(i = 1,2)     
    Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+2)) = Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+2))+((-1)^i1g4)*Ll1*K1y;
    Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+3)) = Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+3))-((-1)^i1g4)*Ll1*H4*K1y;
    Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+5)) = Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+5))+Ll1*Ll1*K1y;
    Klc((20+5*(i1g1-1)+5),(5*(i1g2-1)+2)) = Klc((20+5*(i1g1-1)+5),(5*(i1g2-1)+2))-((-1)^i1g4)*Ll1*K1y;
    %%% 2、7、12、17行：δywm(m = 1,2,3,4)      
    Klc((5*(i1g2-1)+2),(20+5*(i1g1-1)+2)) = Klc((5*(i1g2-1)+2),(20+5*(i1g1-1)+2))-K1y;
    Klc((5*(i1g2-1)+2),(20+5*(i1g1-1)+3)) = Klc((5*(i1g2-1)+2),(20+5*(i1g1-1)+3))+H4*K1y;
    Klc((5*(i1g2-1)+2),(20+5*(i1g1-1)+5)) = Klc((5*(i1g2-1)+2),(20+5*(i1g1-1)+5))-((-1)^i1g4)*Ll1*K1y;
    Klc((5*(i1g2-1)+2),(5*(i1g2-1)+2)) = Klc((5*(i1g2-1)+2),(5*(i1g2-1)+2))+K1y;
    
    %%% 24、29行：δβti(i = 1,2)     
    Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+4)) = Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+4))+H4*H4*K1x;
    Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+5)) = Klc((20+5*(i1g1-1)+4),(20+5*(i1g1-1)+5))+((-1)^(i1+1+1))*Lb1*H4*K1x;
    Klc((20+5*(i1g1-1)+4),(5*(i1g2-1)+5)) = Klc((20+5*(i1g1-1)+4),(5*(i1g2-1)+5))-((-1)^(i1+1+1))*Lb1*H4*K1x;
    %%% 25、30行：δψti(i = 1,2)      
    Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+4)) = Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+4))+((-1)^(i1+1+1))*Lb1*H4*K1x;
    Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+5)) = Klc((20+5*(i1g1-1)+5),(20+5*(i1g1-1)+5))+Lb1*Lb1*K1x;
    Klc((20+5*(i1g1-1)+5),(5*(i1g2-1)+5)) = Klc((20+5*(i1g1-1)+5),(5*(i1g2-1)+5))-Lb1*Lb1*K1x;
    %%% 5、10、15、20行：δψwm(m = 1,2,3,4)     
    Klc((5*(i1g2-1)+5),(20+5*(i1g1-1)+4)) = Klc((5*(i1g2-1)+5),(20+5*(i1g1-1)+4))-((-1)^(i1+1+1))*Lb1*H4*K1x;
    Klc((5*(i1g2-1)+5),(20+5*(i1g1-1)+5)) = Klc((5*(i1g2-1)+5),(20+5*(i1g1-1)+5))-Lb1*Lb1*K1x;
    Klc((5*(i1g2-1)+5),(5*(i1g2-1)+5)) = Klc((5*(i1g2-1)+5),(5*(i1g2-1)+5))+Lb1*Lb1*K1x;
    
    i1=i1+1;
end

%%% 二系悬挂 K2z、K2y、K2x
i1=0;   % i1 = 0:1:3;
while i1<4
    i1g2=fix((i1+1+1)/2);          %%% 构架序号 i=[1,1,2,2]
    i1g3=fix((3*(i1+1)+1)/2);      %%% 车轮位置序号 j+i=2,3,5,6 Left/Right
    i1g4=fix((i1+1-1)/2);          %%% i±1=[0,0,1,1]
    
    %%% 31列：zc
    Klc((30+1),(30+1)) = Klc((30+1),(30+1))+K2z;
    Klc((30+3),(30+1)) = Klc((30+3),(30+1))+((-1)^(i1+1))*Lb2*K2z;
    Klc((30+4),(30+1)) = Klc((30+4),(30+1))+((-1)^i1g2)*Ll2*K2z;
    Klc((20+5*(i1g2-1)+1),(30+1)) = Klc((20+5*(i1g2-1)+1),(30+1))-K2z;
    Klc((20+5*(i1g2-1)+3),(30+1)) = Klc((20+5*(i1g2-1)+3),(30+1))-((-1)^(i1+1))*Lb2*K2z;
    %%% 33列：φc    
    Klc((30+1),(30+3)) = Klc((30+1),(30+3))+((-1)^(i1+1))*Lb2*K2z;
    Klc((30+3),(30+3)) = Klc((30+3),(30+3))+Lb2*Lb2*K2z;
    Klc((30+4),(30+3)) = Klc((30+4),(30+3))+((-1)^i1g3)*Lb2*Ll2*K2z;
    Klc((20+5*(i1g2-1)+1),(30+3)) = Klc((20+5*(i1g2-1)+1),(30+3))-((-1)^(i1+1))*Lb2*K2z;
    Klc((20+5*(i1g2-1)+3),(30+3)) = Klc((20+5*(i1g2-1)+3),(30+3))-Lb2*Lb2*K2z;
    %%% 34列：βc     
    Klc((30+1),(30+4)) = Klc((30+1),(30+4))+((-1)^i1g2)*Ll2*K2z;
    Klc((30+3),(30+4)) = Klc((30+3),(30+4))+((-1)^i1g3)*Lb2*Ll2*K2z;
    Klc((30+4),(30+4)) = Klc((30+4),(30+4))+Ll2*Ll2*K2z;
    Klc((20+5*(i1g2-1)+1),(30+4)) = Klc((20+5*(i1g2-1)+1),(30+4))-((-1)^i1g2)*Ll2*K2z;
    Klc((20+5*(i1g2-1)+3),(30+4)) = Klc((20+5*(i1g2-1)+3),(30+4))-((-1)^i1g3)*Lb2*Ll2*K2z;
    %%% 21、26列：zti(i = 1,2)      
    Klc((30+1),(20+5*(i1g2-1)+1)) = Klc((30+1),(20+5*(i1g2-1)+1))-K2z;
    Klc((30+3),(20+5*(i1g2-1)+1)) = Klc((30+3),(20+5*(i1g2-1)+1))-((-1)^(i1+1))*Lb2*K2z;
    Klc((30+4),(20+5*(i1g2-1)+1)) = Klc((30+4),(20+5*(i1g2-1)+1))-((-1)^i1g2)*Ll2*K2z;
    Klc((20+5*(i1g2-1)+1),(20+5*(i1g2-1)+1)) = Klc((20+5*(i1g2-1)+1),(20+5*(i1g2-1)+1))+K2z;
    Klc((20+5*(i1g2-1)+3),(20+5*(i1g2-1)+1)) = Klc((20+5*(i1g2-1)+3),(20+5*(i1g2-1)+1))+((-1)^(i1+1))*Lb2*K2z;
    %%% 23、27列：φti(i = 1,2)    
    Klc((30+1),(20+5*(i1g2-1)+3)) = Klc((30+1),(20+5*(i1g2-1)+3))-((-1)^(i1+1))*Lb2*K2z;
    Klc((30+3),(20+5*(i1g2-1)+3)) = Klc((30+3),(20+5*(i1g2-1)+3))-Lb2*Lb2*K2z;
    Klc((30+4),(20+5*(i1g2-1)+3)) = Klc((30+4),(20+5*(i1g2-1)+3))-((-1)^i1g3)*Lb2*Ll2*K2z;
    Klc((20+5*(i1g2-1)+1),(20+5*(i1g2-1)+3)) = Klc((20+5*(i1g2-1)+1),(20+5*(i1g2-1)+3))+((-1)^(i1+1))*Lb2*K2z;
    Klc((20+5*(i1g2-1)+3),(20+5*(i1g2-1)+3)) = Klc((20+5*(i1g2-1)+3),(20+5*(i1g2-1)+3))+Lb2*Lb2*K2z;    
    
    %%% 32行：δyc    
    Klc((30+2),(30+2)) = Klc((30+2),(30+2))+K2y;
    Klc((30+2),(30+3)) = Klc((30+2),(30+3))-H2*K2y;
    Klc((30+2),(30+5)) = Klc((30+2),(30+5))+((-1)^i1g4)*Ll2*K2y;
    Klc((30+2),(20+5*(i1g2-1)+2)) = Klc((30+2),(20+5*(i1g2-1)+2))-K2y;
    Klc((30+2),(20+5*(i1g2-1)+3)) = Klc((30+2),(20+5*(i1g2-1)+3))-H3*K2y;
    %%% 33行：δφc      
    Klc((30+3),(30+2)) = Klc((30+3),(30+2))-H2*K2y;
    Klc((30+3),(30+3)) = Klc((30+3),(30+3))+H2*H2*K2y;
    Klc((30+3),(30+5)) = Klc((30+3),(30+5))-((-1)^i1g4)*Ll2*H2*K2y;
    Klc((30+3),(20+5*(i1g2-1)+2)) = Klc((30+3),(20+5*(i1g2-1)+2))+H2*K2y;
    Klc((30+3),(20+5*(i1g2-1)+3)) = Klc((30+3),(20+5*(i1g2-1)+3))+H2*H3*K2y;
    %%% 35行：δψc       
    Klc((30+5),(30+2)) = Klc((30+5),(30+2))+((-1)^i1g4)*Ll2*K2y;
    Klc((30+5),(30+3)) = Klc((30+5),(30+3))-((-1)^i1g4)*Ll2*H2*K2y;
    Klc((30+5),(30+5)) = Klc((30+5),(30+5))+Ll2*Ll2*K2y;
    Klc((30+5),(20+5*(i1g2-1)+2)) = Klc((30+5),(20+5*(i1g2-1)+2))-((-1)^i1g4)*Ll2*K2y;
    Klc((30+5),(20+5*(i1g2-1)+3)) = Klc((30+5),(20+5*(i1g2-1)+3))-((-1)^i1g4)*Ll2*H3*K2y;
    %%% 22、27行：δyti(i = 1,2)     
    Klc((20+5*(i1g2-1)+2),(30+2)) = Klc((20+5*(i1g2-1)+2),(30+2))-K2y;
    Klc((20+5*(i1g2-1)+2),(30+3)) = Klc((20+5*(i1g2-1)+2),(30+3))+H2*K2y;
    Klc((20+5*(i1g2-1)+2),(30+5)) = Klc((20+5*(i1g2-1)+2),(30+5))-((-1)^i1g4)*Ll2*K2y;
    Klc((20+5*(i1g2-1)+2),(20+5*(i1g2-1)+2)) = Klc((20+5*(i1g2-1)+2),(20+5*(i1g2-1)+2))+K2y;
    Klc((20+5*(i1g2-1)+2),(20+5*(i1g2-1)+3)) = Klc((20+5*(i1g2-1)+2),(20+5*(i1g2-1)+3))+H3*K2y;
    %%% 23、28行：δφti(i = 1,2)       
    Klc((20+5*(i1g2-1)+3),(30+2)) = Klc((20+5*(i1g2-1)+3),(30+2))-H3*K2y;
    Klc((20+5*(i1g2-1)+3),(30+3)) = Klc((20+5*(i1g2-1)+3),(30+3))+H2*H3*K2y;
