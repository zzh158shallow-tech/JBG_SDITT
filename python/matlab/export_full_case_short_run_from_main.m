end


function local_cleanup(varargin)
for index = 1:numel(varargin)
    path_value = varargin{index};
    if exist(path_value, 'file')
        delete(path_value);
    end
end
end


function escaped = local_escape_path(path_value)
escaped = strrep(path_value, '''', '''''');
end


function indented = local_indent(text, spaces)
prefix = repmat(' ', 1, spaces);
lines = splitlines(string(text));
for index = 1:numel(lines)
    if strlength(lines(index)) > 0
        lines(index) = prefix + lines(index);
    end
end
indented = char(join(lines, newline));
end
