    '''xcs_PreviousStep'', ''ZP_IntError_Nor'', ''ZP_IntError_NorTan'', ', ...
    '''Pxt_Gravity'', ', ...
    '''Pjc'', ''Pjch'', ''Pjcc'', ''Prhx'', ''Prhxf'', ''Dis_Rail'', ''Vel_Rail'', ''Acc_Rail'', ', ...
    '''ZP_Dis'', ''ZP_Vel'', ''ZP_Acc'', ''ZP_Load'', ''ZP_NF'', ''d0'', ''Con_WS'', ''Con_Int'', ', ...
    '''ShapeFunction'', ''RailBeam_Motion'', ''DynStatus_Rail'', ''-v7'');\n'], ...
    strrep(mat_path, '''', ''''''));
end


